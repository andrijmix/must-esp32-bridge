#!/usr/bin/env python3
"""Embed dash/* into src/dash_assets.h (PROGMEM) so the dashboard is part of the
single firmware .bin, like the existing config page in web_ui.h.

Run after editing anything in dash/:   python tools/gen_dash.py
Chart.js is stored gzip-compressed and served with Content-Encoding: gzip.
"""
import gzip
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DASH = ROOT / "dash"
OUT = ROOT / "src" / "dash_assets.h"

TEXT_ASSETS = [
    ("DASH_INDEX_HTML", DASH / "index.html"),
    ("DASH_APP_JS", DASH / "app.js"),
    ("DASH_STYLE_CSS", DASH / "style.css"),
]
CHART = DASH / "vendor" / "chart.umd.min.js"
DELIM = "DASHRAW"


def main() -> None:
    parts = [
        "#pragma once\n",
        "// GENERATED by tools/gen_dash.py from dash/* -- do not edit by hand.\n",
        "// UI based on VladRoma/must_pv18-3224-settings (MIT); Chart.js 4.4.6 (MIT).\n\n",
        "#include <Arduino.h>\n\n",
    ]
    for ident, path in TEXT_ASSETS:
        text = path.read_text(encoding="utf-8")
        if f"){DELIM}\"" in text:
            raise SystemExit(f"{path.name} contains the raw-string delimiter")
        parts.append(f'static const char {ident}[] PROGMEM = R"{DELIM}({text}){DELIM}";\n\n')

    gz = gzip.compress(CHART.read_bytes(), compresslevel=9, mtime=0)
    rows = []
    for i in range(0, len(gz), 16):
        rows.append("  " + ", ".join(f"0x{b:02x}" for b in gz[i : i + 16]))
    parts.append("static const uint8_t DASH_CHART_JS_GZ[] PROGMEM = {\n" + ",\n".join(rows) + "\n};\n")
    parts.append(f"static const size_t DASH_CHART_JS_GZ_LEN = {len(gz)};\n")

    OUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {OUT.stat().st_size} bytes (chart.js gz {len(gz)} B)")


if __name__ == "__main__":
    main()
